def evidence(
    key: str, relevance: str = "direct", reason: str = "该 Chunk 支持问题中的关键结论。"
) -> dict[str, str]:
    return {"chunk_id": EVIDENCE[key], "relevance": relevance, "reason": reason}


def row(
    index: int,
    question: str,
    domain: str,
    case_type: str,
    answerability: str,
    products: list[str],
    evidence_keys: list[tuple[str, str]],
    points: list[str],
    not_claim: list[str],
    clarifications: list[str],
    safety: str,
) -> dict[str, Any]:
    return {
        "id": f"d6-{index:03d}",
        "question": question,
        "domain": domain,
        "case_type": case_type,
        "answerability": answerability,
        "expected_products": products,
        "gold_evidence": [evidence(key, relevance) for key, relevance in evidence_keys],
        "gold_points": points,
        "must_not_claim": not_claim,
        "required_clarifications": clarifications,
        "safety": safety,
        "split": "",
        "kb_version": "v1",
        "annotation": {
            "annotator": "XYS",
            "reviewer": "self-review",
            "status": "reviewed",
            "notes": "Gold evidence checked against chunks_section.jsonl.",
        },
    }


