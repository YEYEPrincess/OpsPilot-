def main() -> int:
    chunk_ids = {
        json.loads(line)["chunk_id"]
        for line in CHUNKS.read_text(encoding="utf-8").splitlines()
        if line
    }
    rows = build_rows()
    assert len(rows) == 60
    assert len({item["id"] for item in rows}) == 60
    for item in rows:
        for item_evidence in item["gold_evidence"]:
            assert item_evidence["chunk_id"] in chunk_ids, item_evidence
        if item["answerability"] == "answerable":
            assert item["gold_evidence"] and item["gold_points"]
        if item["answerability"] == "unanswerable":
            assert not item["gold_evidence"]
    OUTPUT.write_text(json.dumps(rows, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(
        json.dumps(
            {
                "records": len(rows),
                "case_type": {
                    key: sum(item["case_type"] == key for item in rows)
                    for key in ("simple", "complex", "ambiguous", "unanswerable")
                },
                "split": {
                    key: sum(item["split"] == key for item in rows)
                    for key in ("development", "validation", "test")
                },
            },
            ensure_ascii=False,
            indent=2,
        )
    )
    return 0


